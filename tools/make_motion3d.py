"""Hand trajectories for the II.01 "Không gian chuyển động" 3D view -> data/motion3d.js.

Palm-link path of the active hand (URDF FK from observation.state) in successful episodes of the
real2sim training datasets, 3 per fruit, plus the fruit's start position and the plate.
The fixed pelvis's world offset is fitted at the grasp frames (left/right palms sit on opposite
sides of the fruit, so the two medians are averaged).

Needs numpy + pyarrow:  python tools/make_motion3d.py   (run from report/)"""
import json, sys, glob, os
import numpy as np, pyarrow.parquet as pq
ROOT = "/home/nhathm12/workspace/shimizu-robot/codes/g1_real2sim"
sys.path.insert(0, ROOT)
from g1r2s import config
from g1r2s.scene import G1Kinematics, detect_events

kin = G1Kinematics()
def load(path):
    t = pq.read_table(path).to_pydict()
    st = np.array(t["observation.state"]); fr = np.array(t["observation.sim.fruit_pose"]); pl = np.array(t["observation.sim.plate_pose"])
    return st, fr, pl, t["task_index"][0], all(t["next.success"][-3:]) or any(t["next.success"])

sets = {"apple": ("g1-pick-apple-sim", None), "pear": ("g1-pick-pear-sim", None), "grapes": ("g1-pick-grapes-sim", None), "starfruit": ("demo-g1-pick-sim", 3)}
out, offs = [], []
for fruit, (d, want_task) in sets.items():
    files = sorted(glob.glob(f"{ROOT}/output/{d}/data/chunk-000/*.parquet"))
    n = 0
    for f in files:
        st, fr, pl, ti, ok = load(f)
        if want_task is not None and ti != want_task: continue
        ev = detect_events(st)
        if not ok or ev.active_hand is None or ev.grasp_frame is None or ev.release_frame is None: continue
        T = kin.fk_pelvis(st, [config.PALM_LINKS[ev.active_hand]])[config.PALM_LINKS[ev.active_hand]]
        palm = T[:, :3, 3]
        offs.append((ev.active_hand, fr[ev.grasp_frame, :3] - palm[ev.grasp_frame]))
        out.append(dict(fruit=fruit, ep=os.path.basename(f), hand=ev.active_hand, g=ev.grasp_frame, r=ev.release_frame,
                        palm=palm, fruit0=fr[0, :3], plate=pl[0, :3]))
        n += 1
        if n >= 3: break
per = {h: np.array([o for hh, o in offs if hh == h]) for h in ("left", "right")}
for h, a in per.items(): print(h, "offset median", np.median(a, 0).round(3), "std", a.std(0).round(3), len(a))
# pelvis offset is shared; the palm sits on opposite sides of the fruit for the two hands, so average them
off = (np.median(per["left"], 0) + np.median(per["right"], 0)) / 2
print("pelvis offset", off.round(3))
res = []
for e in out:
    P = e["palm"] + off
    res.append(dict(fruit=e["fruit"], hand=e["hand"], grasp=e["g"], release=e["r"],
                    path=[[round(float(v), 3) for v in p] for p in P[::2]],
                    fruit0=[round(float(v), 3) for v in e["fruit0"]], plate=[round(float(v), 3) for v in e["plate"]]))
    print(e["fruit"], e["ep"], e["hand"], "grasp err cm", round(float(np.linalg.norm(P[e['g']] - e['fruit0'])) * 100, 1), "len", len(P))
js = dict(source="real2sim train datasets (g1-pick-*-sim), palm link via URDF FK; offset fitted at grasp frames", offset=[round(float(v),3) for v in off], episodes=res)
out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "motion3d.js")
with open(out_path, "w") as f:
    f.write("/* Generated by tools/make_motion3d.py; do not edit by hand. */\n"
            "window.Report = window.Report || {};\n"
            "window.Report.motion3d = " + json.dumps(js, ensure_ascii=False) + ";\n")
print("wrote", out_path)
