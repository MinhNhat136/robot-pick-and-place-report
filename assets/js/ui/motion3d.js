/* II.01 "Không gian chuyển động": palm paths of the robot hand in 3D, drawn on a canvas with a
   small hand-rolled perspective camera (no library, the report stays offline).
   Data: window.Report.motion3d, generated by tools/make_motion3d.py from the real2sim training
   datasets (palm link via URDF FK). Drag to orbit; fruit buttons filter; ▶ replays the motion.
   Each path: thin = reaching, thick = carrying (grasp → release), faded = hand going back. */
(function () {
  "use strict";
  const R = window.Report;

  const FRUIT = {
    apple: { name: "Táo", color: "#d9463b" },
    pear: { name: "Lê", color: "#c99a12" },
    grapes: { name: "Nho", color: "#3f9b4a" },
    starfruit: { name: "Khế", color: "#e07b1f" },
  };
  const PLATE_R = 0.115;
  const fmt = (x, d = 1, L = "vi") => (L === "vi" ? x.toFixed(d).replace(".", ",") : x.toFixed(d));
  const TX = {
    vi: { fruit: { apple: "Táo", pear: "Lê", grapes: "Nho", starfruit: "Khế" }, grid: "ô lưới 10 cm", robot: "ROBOT ĐỨNG Ở ĐÂY",
      left: "trái", right: "phải", both: "cả hai", hand: h => `tay ${h}`, lift: v => `nhấc ~${v} cm`, head: (n, k) => `${n} DEMO · ${k} MỖI LOẠI QUẢ`,
      lg: ["Tiến tới quả", "Mang quả", "Rút tay", "Nắm", "Thả"], play: "▶ Phát lại chuyển động", stop: "■ Dừng" },
    en: { fruit: { apple: "Apple", pear: "Pear", grapes: "Grapes", starfruit: "Starfruit" }, grid: "10 cm grid", robot: "ROBOT STANDS HERE",
      left: "left", right: "right", both: "both", hand: h => `${h} hand`, lift: v => `lift ~${v} cm`, head: (n, k) => `${n} DEMOS · ${k} PER FRUIT`,
      lg: ["Reach to fruit", "Carry fruit", "Withdraw hand", "Grasp", "Release"], play: "▶ Replay motion", stop: "■ Stop" },
    ja: { fruit: { apple: "リンゴ", pear: "梨", grapes: "ブドウ", starfruit: "スターフルーツ" }, grid: "グリッド 10 cm", robot: "ロボットの立ち位置",
      left: "左", right: "右", both: "両", hand: h => `${h}手`, lift: v => `持ち上げ ~${v} cm`, head: (n, k) => `${n} デモ · 果物ごとに ${k}`,
      lg: ["果物へ接近", "果物を運搬", "手を戻す", "把持", "解放"], play: "▶ 動作を再生", stop: "■ 停止" },
  };

  function setup(box) {
    const data = R.motion3d;
    const canvas = R.$("canvas", box), ctx = canvas.getContext("2d");
    const out = R.$("[data-m3-out]", box), btns = R.$$("[data-m3-fruit]", box);
    const play = R.$("[data-m3-play]", box), reset = R.$("[data-m3-reset]", box);
    const eps = data.episodes;
    const L = (box.closest("[data-i18n]")?.dataset.i18n) || "vi", tx = TX[L] || TX.vi;
    const tableZ = Math.min(...eps.map(e => e.plate[2])) - 0.005;
    const C = [0.38, 0, tableZ + 0.05];          // orbit centre: middle of the work area
    const VIEW0 = { yaw: 0.35, pitch: 0.75 };
    let view = { ...VIEW0 }, filter = "all", t = 1, timer = null, W = 0, H = 0;

    // world (x fwd, y left, z up) → screen, orbit camera around C
    function project(p) {
      const dx = p[0] - C[0], dy = p[1] - C[1], dz = p[2] - C[2];
      const cy = Math.cos(view.yaw), sy = Math.sin(view.yaw), cp = Math.cos(view.pitch), sp = Math.sin(view.pitch);
      const x1 = dx * cy - dy * sy, y1 = dx * sy + dy * cy;  // yaw about z
      const depth = -x1 * cp + dz * sp;                        // camera stands behind the robot, looking forward
      const up = x1 * sp + dz * cp;
      const f = 2.1 / (2.1 - depth * 1.0);                     // mild perspective
      const s = Math.min(W * 0.62, H) * 1.9;
      return [W / 2 - y1 * s * f, H * 0.5 - up * s * f, depth];
    }
    const line = (pts, color, width, alpha = 1, dash) => {
      ctx.save(); ctx.globalAlpha = alpha; ctx.strokeStyle = color; ctx.lineWidth = width; ctx.lineJoin = ctx.lineCap = "round";
      if (dash) ctx.setLineDash(dash);
      ctx.beginPath(); pts.forEach((p, i) => { const q = project(p); i ? ctx.lineTo(q[0], q[1]) : ctx.moveTo(q[0], q[1]); }); ctx.stroke(); ctx.restore();
    };
    const dot = (p, r, fill, stroke) => { const q = project(p); ctx.beginPath(); ctx.arc(q[0], q[1], r, 0, 7); if (fill) { ctx.fillStyle = fill; ctx.fill(); } if (stroke) { ctx.strokeStyle = stroke; ctx.lineWidth = 2; ctx.stroke(); } };
    const label = (p, txt, color = "#5a6170", dx = 6, dy = -6) => { const q = project(p); ctx.fillStyle = color; ctx.font = "600 11px 'IBM Plex Mono', monospace"; ctx.fillText(txt, q[0] + dx, q[1] + dy); };
    const circle = (c, r, n = 40) => Array.from({ length: n + 1 }, (_, i) => [c[0] + r * Math.cos(i / n * 2 * Math.PI), c[1] + r * Math.sin(i / n * 2 * Math.PI), c[2]]);

    function draw() {
      const dpr = window.devicePixelRatio || 1;
      W = canvas.clientWidth; H = canvas.clientHeight;
      if (!W || !H) return;
      canvas.width = W * dpr; canvas.height = H * dpr; ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      ctx.clearRect(0, 0, W, H);
      // table grid (10 cm) and where the robot stands
      for (let x = 0.15; x <= 0.651; x += 0.1) line([[x, -0.35, tableZ], [x, 0.35, tableZ]], "#d3dae4", 1);
      for (let y = -0.35; y <= 0.351; y += 0.1) line([[0.15, y, tableZ], [0.65, y, tableZ]], "#d3dae4", 1);
      label([0.65, 0.35, tableZ], tx.grid, "#9aa3ad", 6, 4);
      line([[0.15, -0.12, tableZ], [0.15, 0.12, tableZ]], "#7d8794", 4);
      label([0.15, 0, tableZ], tx.robot, "#5a6170", -54, 20);
      line([[0.16, 0, tableZ], [0.27, 0, tableZ]], "#9aa3ad", 1.5, 1, [4, 4]);
      const shown = eps.filter(e => filter === "all" || e.fruit === filter);
      shown.forEach(e => { line(circle(e.plate, PLATE_R), "#5aa9b3", 1.2, filter === "all" ? 0.3 : 0.6); dot(e.fruit0, 6, FRUIT[e.fruit].color); });
      shown.forEach(e => {
        const P = e.path, g = Math.round(e.grasp / 2), r = Math.min(P.length - 1, Math.round(e.release / 2));
        const end = Math.max(1, Math.round(t * (P.length - 1)));
        const c = FRUIT[e.fruit].color;
        line(P.slice(0, Math.min(g, end) + 1), c, 1.6, 0.85);
        if (end > g) line(P.slice(g, Math.min(r, end) + 1), c, 3.6, 1);
        if (end > r) line(P.slice(r, end + 1), c, 1.4, 0.35, [3, 4]);
        if (end >= g) dot(P[g], 4.5, c, "#fff");
        if (end >= r) dot(P[r], 5, "#fff", c);
        if (t < 1) dot(P[end], 5.5, "#1f2a3a", "#fff");
      });
    }

    function stats() {
      const rows = Object.keys(FRUIT).map(k => {
        const es = eps.filter(e => e.fruit === k);
        const lift = es.map(e => Math.max(...e.path.slice(Math.round(e.grasp / 2), Math.round(e.release / 2) + 1).map(p => p[2])) - e.fruit0[2]);
        const hand = es.every(e => e.hand === es[0].hand) ? (es[0].hand === "left" ? tx.left : tx.right) : tx.both;
        const avg = a => a.reduce((s, x) => s + x, 0) / a.length;
        return `<li${filter !== "all" && filter !== k ? ' class="dim"' : ""}><span><i style="background:${FRUIT[k].color}"></i>${tx.fruit[k]} · ${tx.hand(hand)}</span><b>${tx.lift(fmt(avg(lift) * 100, 0, L))}</b></li>`;
      }).join("");
      out.innerHTML = `<span class="ds-k">${tx.head(eps.length, eps.length / 4)}</span><ul>${rows}</ul>
        <div class="m3-legend"><span><em class="thin"></em>${tx.lg[0]}</span><span><em class="thick"></em>${tx.lg[1]}</span><span><em class="back"></em>${tx.lg[2]}</span><span><em class="g"></em>${tx.lg[3]}</span><span><em class="r"></em>${tx.lg[4]}</span></div>`;
    }

    const stop = () => { clearInterval(timer); timer = null; play.textContent = tx.play; };
    btns.forEach(b => b.addEventListener("click", () => {
      filter = b.dataset.m3Fruit; btns.forEach(x => x.setAttribute("aria-pressed", String(x === b))); stats(); draw();
    }));
    play.addEventListener("click", () => {
      if (timer) { stop(); t = 1; draw(); return; }
      t = 0; play.textContent = tx.stop;
      timer = setInterval(() => { t = Math.min(1, t + 0.012); draw(); if (t >= 1) stop(); }, 30);
    });
    reset.addEventListener("click", () => { view = { ...VIEW0 }; draw(); });

    // drag to orbit (pointer events: mouse, pen and touch)
    let drag = null;
    canvas.addEventListener("pointerdown", e => { drag = { x: e.clientX, y: e.clientY, v: { ...view } }; canvas.setPointerCapture(e.pointerId); });
    canvas.addEventListener("pointermove", e => {
      if (!drag) return;
      view.yaw = drag.v.yaw + (e.clientX - drag.x) * 0.008;
      view.pitch = Math.max(0.05, Math.min(1.45, drag.v.pitch + (e.clientY - drag.y) * 0.006));
      draw();
    });
    ["pointerup", "pointercancel"].forEach(ev => canvas.addEventListener(ev, () => { drag = null; }));

    new ResizeObserver(draw).observe(canvas);
    R.on("section:shown", sec => { if (sec.contains(box)) draw(); else stop(); });
    stats(); draw();
  }

  R.motionSpace = {
    init() {
      if (!R.motion3d) return;
      R.$$("[data-m3]").forEach(box => { try { setup(box); } catch (e) { console.error("motion3d", e); } });
    },
  };
})();
